"""Small invented five-trip fixture; no organiser raw data is published."""
from pathlib import Path
import json
import numpy as np
import pandas as pd
from src.data_processing.loaders import load_trip
from src.data_processing.geo import project_trip
from src.features.build import build_features
from src.features.labels import align_labels


def write_fixture(root=Path('tests/fixtures/member1')):
    root = Path(root)
    root.mkdir(parents=True, exist_ok=True)
    tables, labels = [], []
    for i, (lon, lat) in enumerate([(8, 49), (137, 35), (-100, 40), (18, -34), (25, 61)], 1):
        folder = root / f'{i:08d}'
        folder.mkdir(exist_ok=True)
        nodes = np.array([[lon, lat], [lon+.001, lat], [lon+.002, lat], [lon+.001, lat+.001]])
        arcs = np.array([[0, 1], [1, 2], [1, 0], [2, 1], [1, 3], [3, 1]])
        track = np.column_stack([np.linspace(lon+.0001, lon+.0019, 12), np.full(12, lat+.00001), np.arange(12)])
        for extension, values, fmt in [('nodes', nodes, '%.8f'), ('arcs', arcs, '%d'), ('track', track, '%.8f'), ('route', [0, 1], '%d')]:
            np.savetxt(folder / f'{folder.name}.{extension}', values, fmt=fmt)
        metric = project_trip(load_trip(folder, include_route=True))
        lab = align_labels(metric)
        table = build_features(metric, 50, 4)
        table = table.merge(lab[['trip_id', 'obs_idx', 'ref_arc']], on=['trip_id', 'obs_idx'])
        table['is_ref'] = (table.arc_id == table.ref_arc).astype('int8')
        tables.append(table.drop(columns='ref_arc'))
        labels.append(lab)
    pd.concat(tables).to_parquet(root / 'candidates.parquet', index=False)
    pd.concat(labels).to_parquet(root / 'obs_labels.parquet', index=False)
    (root / 'README.md').write_text('Synthetic five-trip fixture generated by `python -m src.data_processing.synthetic`.\nCoordinates and road graphs are invented; this is not organiser data.\n')


if __name__ == '__main__':
    write_fixture()
